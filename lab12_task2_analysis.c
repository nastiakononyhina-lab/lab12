int main()
{
    setlocale(LC_ALL, "Rus");
    float PI = 3.14159, *p1, *p2;
    p1 = p2 = &PI;
    printf("По адресу p1=%p хранится *p1=%g\n", (void*)p1, *p1);
    printf("По адресу p2=%p хранится *p2=%g\n", (void*)p2, *p2);

    // Объяснение результата:
    // В строке p1 = p2 = &PI; оба указателя получают один и тот же адрес
    // переменной PI. Поэтому адреса p1 и p2 в выводе одинаковые, а по этому
    // адресу лежит число 3.14159, поэтому *p1 и *p2 тоже одинаковые.
    // Спецификатор %g печатает число без лишних нулей.

    // то же самое адрес в шестнадцатеричном виде (%x)
    printf("Адрес в 16-ричном виде: %x\n", (unsigned int)(size_t)p1);

    return 0;
}
